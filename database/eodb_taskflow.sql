-- -----------------------------------------------------------------------------
-- Table: departments
-- Lookup table for RHU units/sections. Normalizes users.department.
-- -----------------------------------------------------------------------------
CREATE TABLE `departments` (
  `id`          INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  `name`        VARCHAR(100)  NOT NULL,
  `description` VARCHAR(255)  NULL DEFAULT NULL,
  `created_at`  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_departments_name` (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: users
-- Every person who can log in (admin, supervisor, employee).
-- Accounts are deactivated (status = 'inactive'), never deleted, so task
-- history and reports always remain complete.
-- -----------------------------------------------------------------------------
CREATE TABLE `users` (
  `id`             INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  `employee_id`    VARCHAR(20)   NOT NULL COMMENT 'Office-issued employee number, e.g. RHU-EMP-001',
  `full_name`      VARCHAR(150)  NOT NULL,
  `username`       VARCHAR(50)   NOT NULL,
  `email`          VARCHAR(150)  NOT NULL,
  `password`       VARCHAR(255)  NOT NULL COMMENT 'bcrypt hash from PHP password_hash()',
  `role`           ENUM('admin','supervisor','employee') NOT NULL DEFAULT 'employee',
  `department_id`  INT UNSIGNED  NULL DEFAULT NULL,
  `position`       VARCHAR(100)  NULL DEFAULT NULL,
  `status`         ENUM('active','inactive') NOT NULL DEFAULT 'active',
  `profile_photo`  VARCHAR(255)  NULL DEFAULT NULL COMMENT 'File name inside assets/images/profiles/',
  `last_login_at`  DATETIME      NULL DEFAULT NULL,
  `created_at`     DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at`     DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_users_employee_id` (`employee_id`),
  UNIQUE KEY `uq_users_username`    (`username`),
  UNIQUE KEY `uq_users_email`       (`email`),
  KEY `idx_users_role_status` (`role`, `status`),
  KEY `idx_users_department`  (`department_id`),
  KEY `idx_users_full_name`   (`full_name`),
  CONSTRAINT `fk_users_department`
    FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: tasks
-- Core task record. Status rules (Algorithm 3):
--   progress = 100                    -> Completed
--   CURDATE() > deadline (not done)   -> Overdue   (progress is preserved)
--   progress > 0                      -> In Progress
--   otherwise                         -> Pending
-- -----------------------------------------------------------------------------
CREATE TABLE `tasks` (
  `id`            INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  `task_code`     VARCHAR(20)      NOT NULL COMMENT 'Generated code, e.g. TASK-2026-0001',
  `title`         VARCHAR(200)     NOT NULL,
  `description`   TEXT             NULL,
  `assigned_by`   INT UNSIGNED     NOT NULL COMMENT 'Supervisor who created/assigned the task',
  `assigned_to`   INT UNSIGNED     NOT NULL COMMENT 'Employee responsible for the task',
  `priority`      ENUM('Low','Medium','High','Urgent') NOT NULL DEFAULT 'Medium',
  `deadline`      DATE             NOT NULL,
  `status`        ENUM('Pending','In Progress','Completed','Overdue') NOT NULL DEFAULT 'Pending',
  `progress`      TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0 to 100 percent',
  `remarks`       TEXT             NULL,
  `created_at`    DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at`    DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `completed_at`  DATETIME         NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_tasks_task_code` (`task_code`),
  KEY `idx_tasks_assigned_to_status` (`assigned_to`, `status`),
  KEY `idx_tasks_assigned_by`  (`assigned_by`),
  KEY `idx_tasks_status`       (`status`),
  KEY `idx_tasks_priority`     (`priority`),
  KEY `idx_tasks_deadline`     (`deadline`),
  KEY `idx_tasks_created_at`   (`created_at`),
  KEY `idx_tasks_completed_at` (`completed_at`),
  CONSTRAINT `chk_tasks_progress` CHECK (`progress` BETWEEN 0 AND 100),
  CONSTRAINT `fk_tasks_assigned_by`
    FOREIGN KEY (`assigned_by`) REFERENCES `users` (`id`)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT `fk_tasks_assigned_to`
    FOREIGN KEY (`assigned_to`) REFERENCES `users` (`id`)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: task_updates
-- Task history / audit trail. One row per change of status or progress.
-- user_id is NULL when the change was made automatically by the system
-- (e.g. overdue detection).
-- -----------------------------------------------------------------------------
CREATE TABLE `task_updates` (
  `id`                 INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  `task_id`            INT UNSIGNED     NOT NULL,
  `user_id`            INT UNSIGNED     NULL DEFAULT NULL COMMENT 'NULL = automatic system update',
  `previous_status`    ENUM('Pending','In Progress','Completed','Overdue') NULL DEFAULT NULL COMMENT 'NULL on task creation',
  `new_status`         ENUM('Pending','In Progress','Completed','Overdue') NOT NULL,
  `previous_progress`  TINYINT UNSIGNED NULL DEFAULT NULL COMMENT 'NULL on task creation',
  `new_progress`       TINYINT UNSIGNED NOT NULL,
  `remarks`            TEXT             NULL,
  `updated_at`         DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_task_updates_task` (`task_id`, `updated_at`),
  KEY `idx_task_updates_user` (`user_id`),
  CONSTRAINT `chk_task_updates_prev_progress` CHECK (`previous_progress` IS NULL OR `previous_progress` BETWEEN 0 AND 100),
  CONSTRAINT `chk_task_updates_new_progress`  CHECK (`new_progress` BETWEEN 0 AND 100),
  CONSTRAINT `fk_task_updates_task`
    FOREIGN KEY (`task_id`) REFERENCES `tasks` (`id`)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT `fk_task_updates_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`id`)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: notifications
-- In-app notifications (Algorithm 5). task_id becomes NULL if the related
-- task is deleted so the notification history is kept.
-- -----------------------------------------------------------------------------
CREATE TABLE `notifications` (
  `id`          INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  `user_id`     INT UNSIGNED  NOT NULL COMMENT 'Recipient',
  `task_id`     INT UNSIGNED  NULL DEFAULT NULL,
  `title`       VARCHAR(150)  NOT NULL,
  `message`     VARCHAR(500)  NOT NULL,
  `type`        ENUM('task_assigned','deadline_upcoming','task_overdue','task_completed','task_updated','system')
                NOT NULL DEFAULT 'system',
  `is_read`     TINYINT(1)    NOT NULL DEFAULT 0,
  `created_at`  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_notifications_user_read` (`user_id`, `is_read`, `created_at`),
  KEY `idx_notifications_task_type` (`task_id`, `type`),
  CONSTRAINT `fk_notifications_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`id`)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT `fk_notifications_task`
    FOREIGN KEY (`task_id`) REFERENCES `tasks` (`id`)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: activity_logs
-- Audit trail of user actions. user_id is NULL for system events or failed
-- logins with an unknown username.
-- Action codes: login, login_failed, logout, create_task, assign_task,
-- update_task, complete_task, delete_task, add_user, edit_user,
-- deactivate_user, activate_user, update_profile, update_settings, system
-- -----------------------------------------------------------------------------
CREATE TABLE `activity_logs` (
  `id`           INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  `user_id`      INT UNSIGNED  NULL DEFAULT NULL,
  `action`       VARCHAR(50)   NOT NULL,
  `description`  VARCHAR(500)  NOT NULL,
  `ip_address`   VARCHAR(45)   NULL DEFAULT NULL COMMENT 'IPv4 or IPv6',
  `created_at`   DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_activity_logs_user`       (`user_id`),
  KEY `idx_activity_logs_action`     (`action`),
  KEY `idx_activity_logs_created_at` (`created_at`),
  CONSTRAINT `fk_activity_logs_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`id`)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: remember_tokens
-- Secure "Remember me" (selector + SHA-256 hashed validator). The raw
-- validator only exists in the user's cookie, never in the database.
-- -----------------------------------------------------------------------------
CREATE TABLE `remember_tokens` (
  `id`                INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id`           INT UNSIGNED NOT NULL,
  `selector`          CHAR(24)     NOT NULL,
  `hashed_validator`  CHAR(64)     NOT NULL,
  `expires_at`        DATETIME     NOT NULL,
  `created_at`        DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_remember_tokens_selector` (`selector`),
  KEY `idx_remember_tokens_user`    (`user_id`),
  KEY `idx_remember_tokens_expires` (`expires_at`),
  CONSTRAINT `fk_remember_tokens_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`id`)
    ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: login_attempts
-- Failed login attempts, used to temporarily lock out brute-force attempts.
-- -----------------------------------------------------------------------------
CREATE TABLE `login_attempts` (
  `id`            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `username`      VARCHAR(150) NOT NULL,
  `ip_address`    VARCHAR(45)  NOT NULL,
  `attempted_at`  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_login_attempts_ip`       (`ip_address`, `attempted_at`),
  KEY `idx_login_attempts_username` (`username`, `attempted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- Table: settings
-- Key/value system settings managed by the Administrator.
-- -----------------------------------------------------------------------------
CREATE TABLE `settings` (
  `setting_key`    VARCHAR(100) NOT NULL,
  `setting_value`  VARCHAR(500) NOT NULL,
  `description`    VARCHAR(255) NULL DEFAULT NULL,
  `updated_at`     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`setting_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- View: vw_employee_productivity  (Algorithm 4)
-- Completion Rate = Completed Tasks / Total Tasks x 100
-- For monitoring and reporting only - not a disciplinary score.
-- -----------------------------------------------------------------------------
CREATE VIEW `vw_employee_productivity` AS
SELECT
  u.`id`            AS `user_id`,
  u.`employee_id`   AS `employee_id`,
  u.`full_name`     AS `full_name`,
  u.`position`      AS `position`,
  d.`name`          AS `department`,
  u.`status`        AS `account_status`,
  COUNT(t.`id`)                                         AS `total_tasks`,
  COALESCE(SUM(t.`status` = 'Completed'), 0)            AS `completed_tasks`,
  COALESCE(SUM(t.`status` = 'Pending'), 0)              AS `pending_tasks`,
  COALESCE(SUM(t.`status` = 'In Progress'), 0)          AS `in_progress_tasks`,
  COALESCE(SUM(t.`status` = 'Overdue'), 0)              AS `overdue_tasks`,
  CASE
    WHEN COUNT(t.`id`) = 0 THEN 0.00
    ELSE ROUND(SUM(t.`status` = 'Completed') / COUNT(t.`id`) * 100, 2)
  END                                                   AS `completion_rate`
FROM `users` u
LEFT JOIN `departments` d ON d.`id` = u.`department_id`
LEFT JOIN `tasks` t       ON t.`assigned_to` = u.`id`
WHERE u.`role` = 'employee'
GROUP BY u.`id`, u.`employee_id`, u.`full_name`, u.`position`, d.`name`, u.`status`;

